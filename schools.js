/**
 * 用學校名稱查機關代碼。
 * 名冊上的寫法和對照表未必完全一致（臺／台、區名有無），
 * 所以完全比對之後還會再試幾種寬鬆的比法。
 */
function lookupSchoolCode(name) {
  if (!name) return '';
  const norm = s => String(s)
    .replace(/[臺]/g, '台')
    .replace(/[\s（）()]/g, '');

  const target = norm(name);
  if (SCHOOL_CODES[name]) return SCHOOL_CODES[name];

  for (const [k, v] of Object.entries(SCHOOL_CODES)) {
    if (norm(k) === target) return v;
  }
  // 名冊可能寫簡稱「三侯國小」，對照表是全名「高雄市湖內區三侯國民小學」。
  // 拆成「校名 + 學制」兩段比，才不會讓「三侯」誤中其他含該字的學校。
  const abbr = target.match(/([\u4e00-\u9fa5]{2,6})(國小|國中|高中|高工|高商|幼兒園)$/);
  if (abbr) {
    const [, base, kind] = abbr;
    const full = { 國小: '國民小學', 國中: '國民中學', 高中: '高級中學' }[kind] || kind;
    const hits = Object.entries(SCHOOL_CODES).filter(([k]) => {
      const n = norm(k);
      return n.includes(base) && (n.includes(full) || n.includes(kind));
    });
    if (hits.length === 1) return hits[0][1];   // 唯一才採用，多間相符不亂猜
  }
  return '';
}
